print(f'Introduce el valor de tres números para calcular la media de ellos')

valor1 = float(input(f'Introduce el valor 1 = '))
valor2 = float(input(f'Introduce el valor 2 = '))
valor3 = float(input(f'Introduce el valor 3 = '))


Suma = valor1 + valor2 + valor3
Media= Suma / 3

print(f'La media de los 3 números es {Media}')
