print(f'Introduce los catetos del Triángulo Rectángulo')

lado = float(input(f'Introduce el valor de la altura = '))
base = float(input(f'Introduce el valor de la base = '))

Hipotenusa= (lado * lado ) + (base * base)

h= Hipotenusa ** 0.5 
print(f'La Hipotenusa de tu triángulo rectángulo es {h}') 

